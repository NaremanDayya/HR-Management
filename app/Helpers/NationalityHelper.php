    public static function normalize(?string $nationality): string
    {
        if (! $nationality) {
            return 'غير محدد';
        }

        $trimmed = trim($nationality);
        $lower   = mb_strtolower($trimmed);

        foreach (self::$map as $variant => $canonical) {
            if (mb_strtolower($variant) === $lower) {
                return $canonical;
            }
        }

        return $trimmed; // return as-is if no mapping found
    }
